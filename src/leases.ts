import {canonicalResolutionJson, resolutionCheck, resolutionDigest} from './resolutionAudit.ts';
import {normalizeWorkflow} from './workflow.ts';
import type {WorkflowOracle, WorkflowCompletion} from './workflow.ts';
import {oracleVerificationRuntime} from './workflowRuntime.ts';
import {leaseRuntime} from './leaseRuntime.ts';
import {TransactionHashVariant} from 'genlayer-js/types';

type Hex = `0x${string}`;
type OracleSnapshot = WorkflowCompletion['oracles'][number];
export type LeaseCapability = {
  id: string; subject: Hex; resourceHash: Hex; oracles: string[];
  leaseSeconds: number; maxUses: number;
};
export type LeaseInput = {gateId: string; controller: Hex; oracles: WorkflowOracle[]; capabilities: LeaseCapability[]; className?: string};
export type LeaseManifest = {version: 1; kind: 'GAVEL_LEASE_GATE'; gateId: string; controller: Hex; oracles: WorkflowOracle[]; capabilities: LeaseCapability[]};
type LeaseIdentity = {version: 1; gateId: string; manifestHash: Hex; chainId: number; contractAddress: Hex; capabilityId: string; subject: Hex; resourceHash: Hex};
export type LeaseGrant = LeaseIdentity & {kind: 'LEASE_GRANT'; epoch: number; issuedAt: number; expiresAt: number;
  usedAtGrant: number; previousGrantHash: Hex | null; oracles: OracleSnapshot[]; grantHash: Hex};
export type LeaseConsumption = LeaseIdentity & {kind: 'LEASE_CONSUMPTION'; epoch: number; grantHash: Hex;
  requestId: Hex; consumedAt: number; sequence: number; oracles: OracleSnapshot[]; receiptHash: Hex};
export type LeaseRevocation = LeaseIdentity & {kind: 'LEASE_REVOCATION'; epoch: number; reasonHash: Hex; revokedAt: number; revocationHash: Hex};
export type LeaseState = LeaseIdentity & {epoch: number; used: number; maxUses: number; revoked: boolean};
export type LeasePreview = LeaseState & {status: 'NOT_OPEN' | 'ACTIVE' | 'EXPIRED' | 'EXHAUSTED' | 'REVOKED' | 'BLOCKED'; blockers: string[]; expiresAt?: number};
export type LeaseReader = {getChainId(): Promise<number | string>;
  readContract(request: {address: Hex; functionName: string; args: (string | number)[]; transactionHashVariant: TransactionHashVariant}): Promise<unknown>};
const hex = (value: unknown, size: number): value is Hex => typeof value === 'string' && new RegExp(`^0x[0-9a-f]{${size}}$`).test(value);
const integer = (value: unknown, min: number, max = Number.MAX_SAFE_INTEGER): value is number => Number.isSafeInteger(value) && (value as number) >= min && (value as number) <= max;
const clone = <T>(value: T): T => JSON.parse(canonicalResolutionJson(value));

/** Bounded, immutable capability policy. maxUses is lifetime, not per renewal. */
export function normalizeLeasePolicy(input: LeaseInput): LeaseManifest {
  resolutionCheck(input && (!('version' in input) || input.version === 1)
    && (!('kind' in input) || input.kind === 'GAVEL_LEASE_GATE'), 'INVALID_LEASE_VERSION');
  resolutionCheck(typeof input.controller === 'string' && /^0x[0-9a-f]{40}$/i.test(input.controller)
    && !/^0x0{40}$/i.test(input.controller), 'INVALID_LEASE_CONTROLLER');
  resolutionCheck(Array.isArray(input.capabilities) && input.capabilities.length >= 1 && input.capabilities.length <= 16, 'INVALID_LEASE_CAPABILITIES');
  for (const capability of input.capabilities) {
    resolutionCheck(capability && integer(capability.leaseSeconds, 30, 86400)
      && integer(capability.maxUses, 1, 1_000_000), 'INVALID_LEASE_LIMITS');
  }
  // Reuse the existing identity, source policy, uniqueness and bounds checks.
  const normalized = normalizeWorkflow({workflowId: input.gateId, oracles: input.oracles,
    checkpoints: input.capabilities.map(c => ({id: c.id, actor: c.subject, artifactHash: c.resourceHash, requires: [], oracles: c.oracles}))});
  const capabilities = normalized.checkpoints.map(c => {
    const original = input.capabilities.find(item => item.id === c.id)!;
    return {id: c.id, subject: c.actor, resourceHash: c.artifactHash, oracles: c.oracles,
      leaseSeconds: original.leaseSeconds, maxUses: original.maxUses};
  });
  return clone({version: 1, kind: 'GAVEL_LEASE_GATE', gateId: normalized.workflowId,
    controller: input.controller.toLowerCase() as Hex, oracles: normalized.oracles, capabilities});
}

/** Generate an expiring, revocable job-admission gate. No external job executes. */
export function generateLeaseContract(input: LeaseInput) {
  const manifest = normalizeLeasePolicy(input);
  const className = input.className ?? 'GavelLeaseGate';
  resolutionCheck(typeof className === 'string' && /^[A-Z][A-Za-z0-9]{2,63}$/.test(className), 'INVALID_LEASE_CLASS');
  const manifestHash = resolutionDigest(manifest);
  const literal = JSON.stringify(canonicalResolutionJson(manifest));
  const source = `# { "Depends": "py-genlayer:1jb45aa8ynh2a9c9xn3b7qqh8sm5q93hwfp7jqmwsfhh8jpz09h6" }\n\n# Generated by gavel-judgment-sdk. Immutable lease policy.\nfrom genlayer import *\nimport json\nimport hashlib\n\nMANIFEST_JSON = ${literal}\nMANIFEST_HASH = "${manifestHash}"\n${oracleVerificationRuntime}\n${leaseRuntime.replace('__LEASE_CLASS__', className)}`;
  return {className, source, manifest, manifestHash};
}

function identity(manifest: LeaseManifest, record: LeaseIdentity) {
  resolutionCheck(record && record.version === 1 && record.gateId === manifest.gateId
    && record.manifestHash === resolutionDigest(manifest) && integer(record.chainId, 1)
    && hex(record.contractAddress, 40) && !/^0x0{40}$/.test(record.contractAddress), 'LEASE_RECEIPT_IDENTITY');
  const capability = manifest.capabilities.find(c => c.id === record.capabilityId);
  resolutionCheck(capability && record.subject === capability.subject && record.resourceHash === capability.resourceHash, 'LEASE_RECEIPT_EFFECT');
  return capability;
}
function snapshots(manifest: LeaseManifest, capability: LeaseCapability, records: OracleSnapshot[], time: number) {
  resolutionCheck(Array.isArray(records) && canonicalResolutionJson(records.map(r => r.id)) === canonicalResolutionJson(capability.oracles), 'LEASE_RECEIPT_ORACLES');
  for (const record of records) {
    const policy = manifest.oracles.find(o => o.id === record.id)!;
    resolutionCheck(record.contractAddress === policy.contractAddress && record.specHash === policy.expectedSpecHash
      && policy.allowedOutcomes.includes(record.outcomeId) && hex(record.evidenceDigest, 64)
      && integer(record.observedAt, 1) && record.observedAt <= time && time - record.observedAt <= policy.maxAgeSeconds, 'LEASE_RECEIPT_ORACLE_POLICY');
  }
}
/** Integrity and policy checks only. JSON hashes do not authenticate finality. */
export function auditLeaseGrant(input: LeaseManifest, grant: LeaseGrant) {
  const manifest = normalizeLeasePolicy(input);
  const capability = identity(manifest, grant);
  resolutionCheck(grant.kind === 'LEASE_GRANT' && integer(grant.epoch, 1, 4294967295)
    && integer(grant.issuedAt, 1) && integer(grant.expiresAt, grant.issuedAt + 1, grant.issuedAt + capability.leaseSeconds)
    && integer(grant.usedAtGrant, 0, capability.maxUses - 1)
    && (grant.epoch === 1 ? grant.previousGrantHash === null && grant.usedAtGrant === 0 : hex(grant.previousGrantHash, 64)), 'LEASE_GRANT_BOUNDS');
  snapshots(manifest, capability, grant.oracles, grant.issuedAt);
  resolutionCheck(grant.oracles.every(record => grant.expiresAt <= record.observedAt
    + manifest.oracles.find(o => o.id === record.id)!.maxAgeSeconds), 'LEASE_GRANT_FRESHNESS');
  const {grantHash, ...body} = grant;
  resolutionCheck(resolutionDigest(body) === grantHash, 'LEASE_GRANT_HASH');
  return {integrity: 'VERIFIED' as const, finality: 'CLAIMED_ONLY' as const, grantHash};
}

export function auditLeaseConsumption(input: LeaseManifest, grant: LeaseGrant, receipt: LeaseConsumption) {
  const manifest = normalizeLeasePolicy(input);
  auditLeaseGrant(manifest, grant);
  const capability = identity(manifest, receipt);
  resolutionCheck(receipt.kind === 'LEASE_CONSUMPTION' && receipt.capabilityId === grant.capabilityId
    && receipt.chainId === grant.chainId && receipt.contractAddress === grant.contractAddress
    && receipt.epoch === grant.epoch && receipt.grantHash === grant.grantHash && hex(receipt.requestId, 64), 'LEASE_CONSUMPTION_BINDING');
  resolutionCheck(integer(receipt.consumedAt, grant.issuedAt, grant.expiresAt - 1)
    && integer(receipt.sequence, grant.usedAtGrant + 1, capability.maxUses), 'LEASE_CONSUMPTION_WINDOW');
  snapshots(manifest, capability, receipt.oracles, receipt.consumedAt);
  const {receiptHash, ...body} = receipt;
  resolutionCheck(resolutionDigest(body) === receiptHash, 'LEASE_CONSUMPTION_HASH');
  return {integrity: 'VERIFIED' as const, finality: 'CLAIMED_ONLY' as const, requestId: receipt.requestId, receiptHash};
}

export function auditLeaseRevocation(input: LeaseManifest, record: LeaseRevocation) {
  const manifest = normalizeLeasePolicy(input);
  identity(manifest, record);
  resolutionCheck(record.kind === 'LEASE_REVOCATION' && integer(record.epoch, 0, 4294967295)
    && integer(record.revokedAt, 1) && hex(record.reasonHash, 64), 'LEASE_REVOCATION_BOUNDS');
  const {revocationHash, ...body} = record;
  resolutionCheck(resolutionDigest(body) === revocationHash, 'LEASE_REVOCATION_HASH');
  return {integrity: 'VERIFIED' as const, finality: 'CLAIMED_ONLY' as const, revocationHash};
}

/** Finalized reads and unsigned requests. The application owns signing/fees. */
export function createLeaseClient(config: {reader: LeaseReader; chainId: number; contractAddress: Hex; expectedManifest: LeaseManifest}) {
  const {reader, chainId} = config;
  const contractAddress = config.contractAddress.toLowerCase() as Hex;
  const manifest = normalizeLeasePolicy(config.expectedManifest);
  const manifestHash = resolutionDigest(manifest);
  resolutionCheck(integer(chainId, 1) && hex(contractAddress, 40) && !/^0x0{40}$/.test(contractAddress), 'INVALID_LEASE_DEPLOYMENT');
  const capability = (id: string) => {
    resolutionCheck(manifest.capabilities.some(c => c.id === id), 'UNKNOWN_CAPABILITY');
    return manifest.capabilities.find(c => c.id === id)!;
  };
  async function read(functionName: string, args: (string | number)[]) {
    let raw: unknown;
    try {
      resolutionCheck(Number(await reader.getChainId()) === chainId, 'LEASE_CHAIN_MISMATCH');
      raw = await reader.readContract({address: contractAddress, functionName, args, transactionHashVariant: TransactionHashVariant.LATEST_FINAL});
    } catch (error) {
      if ((error as {code?: string}).code === 'LEASE_CHAIN_MISMATCH') throw error;
      throw new Error('LEASE_RPC_READ_FAILED');
    }
    try {
      resolutionCheck(typeof raw !== 'string' || raw.length <= 1_000_000, 'LEASE_RESPONSE_BOUNDS');
      return typeof raw === 'string' ? JSON.parse(raw) : raw;
    } catch { throw new Error('LEASE_INVALID_JSON'); }
  }
  async function verifyManifest() { resolutionCheck(resolutionDigest(await read('get_manifest', [])) === manifestHash, 'LEASE_MANIFEST_MISMATCH'); }
  function deployment(record: LeaseIdentity) {
    identity(manifest, record);
    resolutionCheck(record.chainId === chainId && record.contractAddress === contractAddress, 'LEASE_DEPLOYMENT_MISMATCH');
  }
  const request = (functionName: string, args: (string | number)[]) => ({address: contractAddress, functionName, args, value: 0n});
  return {
    manifest: clone(manifest),
    async preview(id: string) {
      const policy = capability(id); await verifyManifest();
      const result = await read('preview', [id]) as LeasePreview;
      deployment(result);
      resolutionCheck(result.capabilityId === id && integer(result.epoch, 0, 4294967295)
        && integer(result.used, 0, policy.maxUses) && result.maxUses === policy.maxUses && typeof result.revoked === 'boolean'
        && ['NOT_OPEN', 'ACTIVE', 'EXPIRED', 'EXHAUSTED', 'REVOKED', 'BLOCKED'].includes(result.status)
        && Array.isArray(result.blockers) && result.blockers.every(b => typeof b === 'string')
        && (result.status === 'ACTIVE' ? result.blockers.length === 0 && result.epoch > 0 && result.used < policy.maxUses && !result.revoked && integer(result.expiresAt, 1) : result.blockers.length > 0), 'INVALID_LEASE_PREVIEW');
      return {value: result, state: 'FINALIZED_STATE' as const, advisory: true as const};
    },
    async grant(id: string, epoch: number) {
      capability(id); resolutionCheck(integer(epoch, 1, 4294967295), 'INVALID_LEASE_EPOCH'); await verifyManifest();
      const value = await read('get_grant', [id, epoch]) as LeaseGrant;
      deployment(value); auditLeaseGrant(manifest, value);
      resolutionCheck(value.capabilityId === id && value.epoch === epoch, 'LEASE_GRANT_MISMATCH');
      return {value, state: 'FINALIZED_STATE' as const};
    },
    async consumption(id: string, requestId: Hex) {
      capability(id); resolutionCheck(hex(requestId, 64), 'INVALID_REQUEST_ID'); await verifyManifest();
      const value = await read('get_consumption', [id, requestId]) as LeaseConsumption;
      deployment(value);
      resolutionCheck(value.capabilityId === id && value.requestId === requestId && integer(value.epoch, 1, 4294967295), 'LEASE_REQUEST_MISMATCH');
      const grant = await read('get_grant', [id, value.epoch]) as LeaseGrant;
      auditLeaseConsumption(manifest, grant, value);
      return {value, grant, state: 'FINALIZED_STATE' as const};
    },
    async revocation(id: string) {
      capability(id); await verifyManifest();
      const value = await read('get_revocation', [id]) as LeaseRevocation;
      deployment(value); auditLeaseRevocation(manifest, value);
      resolutionCheck(value.capabilityId === id, 'LEASE_REVOCATION_MISMATCH');
      return {value, state: 'FINALIZED_STATE' as const};
    },
    renewRequest(id: string, expectedEpoch: number) {
      capability(id); resolutionCheck(integer(expectedEpoch, 0, 4294967294), 'INVALID_LEASE_EPOCH');
      return request('renew', [id, expectedEpoch]);
    },
    consumeRequest(id: string, expectedEpoch: number, requestId: Hex) {
      capability(id); resolutionCheck(integer(expectedEpoch, 1, 4294967295) && hex(requestId, 64), 'INVALID_LEASE_REQUEST');
      return request('consume', [id, expectedEpoch, requestId]);
    },
    revokeRequest(id: string, reasonHash: Hex) {
      capability(id); resolutionCheck(hex(reasonHash, 64), 'INVALID_REVOCATION_REASON');
      return request('revoke', [id, reasonHash]);
    },
  };
}
